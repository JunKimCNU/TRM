"""Coordinate-only annotation against a hash-bound exact repeat endpoint audit.

The audit covers declared assembly end windows for one motif family. Reference
span overlap is not a read-base fraction, a uniqueness test, or terminal proof.
"""
import hashlib
import json
from pathlib import Path
import re


METHOD = 'Exact periodic end-window matching, independent of TRM native scan and assessment'
COORDINATES = 'zero-based half-open; distance to raw FASTA endpoint, including terminal Ns/gaps'


def integer(value, label, minimum=0):
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ValueError(f'{label} must be an integer >= {minimum}')
    return value


def canonical(motif):
    """Same rotation/RC equivalence as src/motif.rs; do not alter repeat period."""
    if not isinstance(motif, str) or not motif or set(motif) - set('ACGT'):
        raise ValueError('motif must be nonempty uppercase ACGT')
    reverse = motif.translate(str.maketrans('ACGT', 'TGCA'))[::-1]
    return min(s[i:] + s[:i] for s in (motif, reverse) for i in range(len(s)))


def union_intervals(intervals):
    """Merge overlapping/adjacent half-open intervals, counting each base once."""
    merged = []
    for start, end in sorted(intervals):
        integer(start, 'interval start')
        integer(end, 'interval end', 1)
        if start >= end:
            raise ValueError('interval must be nonempty')
        if merged and start <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], end)
        else:
            merged.append([start, end])
    return merged


def intersect(intervals, start, end):
    return [[max(start, a), min(end, b)] for a, b in intervals
            if max(start, a) < min(end, b)]


def span(intervals):
    return sum(b - a for a, b in intervals)


def unique_object(pairs):
    obj = {}
    for key, value in pairs:
        if key in obj:
            raise ValueError('duplicate JSON key: ' + key)
        obj[key] = value
    return obj


def load_repeat_audit(path, assembly_sha256, family_key, assembly_lengths):
    """Validate the audit and return intervals plus serializable provenance.

    The caller supplies the verified SHA-256 of the mapped assembly bytes and
    actual FASTA lengths. No sequence is loaded or generated by this module.
    """
    if not isinstance(assembly_sha256, str) or not re.fullmatch('[0-9a-f]{64}', assembly_sha256):
        raise ValueError('invalid expected assembly SHA-256')
    if canonical(family_key) != family_key:
        raise ValueError('expected family_key must be canonical')
    if not isinstance(assembly_lengths, dict) or not assembly_lengths:
        raise ValueError('actual assembly lengths are required')
    for name, length in assembly_lengths.items():
        if not isinstance(name, str) or not name:
            raise ValueError('invalid assembly identifier')
        integer(length, 'assembly length', 1)
    raw = Path(path).read_bytes()
    audit = json.loads(raw, object_pairs_hook=unique_object)
    if not isinstance(audit, dict) or type(audit.get('schema_version')) is not int or audit['schema_version'] != 1:
        raise ValueError('unsupported repeat audit schema')
    if audit.get('method') != METHOD or audit.get('coordinate_system') != COORDINATES:
        raise ValueError('unsupported repeat audit method/coordinates')
    settings = audit.get('settings', {})
    if not isinstance(settings, dict):
        raise ValueError('invalid audit settings')
    window = integer(settings.get('window_bp'), 'audit window', 1)
    min_copies = integer(settings.get('min_complete_copies'), 'minimum complete copies', 1)
    assemblies = audit.get('assemblies')
    if not isinstance(assemblies, list) or any(not isinstance(a, dict) for a in assemblies):
        raise ValueError('invalid audit assemblies')
    selected = [a for a in assemblies if a.get('input_sha256') == assembly_sha256]
    if len(selected) != 1:
        raise ValueError('audit must contain exactly one assembly matching verified SHA-256')
    selected = selected[0]
    motif = selected.get('expected_outward_motif')
    if canonical(motif) != family_key:
        raise ValueError('audit motif family does not match exported family')
    period = len(motif)
    if selected.get('full_fasta_parsed') is not True or selected.get('reported_sequence_lengths_all_match') is not True:
        raise ValueError('audit must report complete FASTA parsing and matching lengths')
    contigs = selected.get('contigs')
    if not isinstance(contigs, list) or any(not isinstance(c, dict) for c in contigs):
        raise ValueError('invalid audit contigs')
    lengths = {}
    windows = {}
    for contig in contigs:
        name = contig.get('contig_id')
        if not isinstance(name, str) or not name or name in lengths:
            raise ValueError('missing or duplicate audit contig identifier')
        length = integer(contig.get('length_bp'), 'audit contig length', 1)
        lengths[name] = length
        windows[name] = union_intervals([[0, min(window, length)], [max(0, length-window), length]])
    if lengths != assembly_lengths:
        raise ValueError('audit contig names/lengths do not match actual assembly')
    hits = selected.get('hits')
    if not isinstance(hits, list) or any(not isinstance(h, dict) for h in hits):
        raise ValueError('invalid repeat audit hits')
    intervals = {name: [] for name in lengths}
    for hit in hits:
        name = hit.get('contig_id')
        if not isinstance(name, str) or name not in lengths:
            raise ValueError('audit hit names unknown contig')
        start = integer(hit.get('start_0based'), 'hit start')
        end = integer(hit.get('end_0based_exclusive'), 'hit end', 1)
        if not start < end <= lengths[name] or not any(a <= start < end <= b for a, b in windows[name]):
            raise ValueError('audit hit lies outside contig or declared end windows')
        bp = end-start
        if integer(hit.get('tract_bp'), 'tract length', 1) != bp:
            raise ValueError('hit length disagrees with coordinates')
        copies = integer(hit.get('complete_copies'), 'complete copies', 1)
        partial = integer(hit.get('partial_copy_bp'), 'partial copy bases')
        if copies != bp // period or partial != bp % period or copies < min_copies:
            raise ValueError('hit copy counts disagree with period or minimum')
        rotation = hit.get('matched_rotation')
        if canonical(rotation) != family_key or len(rotation) != period:
            raise ValueError('hit rotation is outside selected motif family')
        if hit.get('strand') not in {'+', '-', '+/-', '-/+'}:
            raise ValueError('invalid hit strand')
        for key in ('window_censored_left', 'window_censored_right'):
            if type(hit.get(key)) is not bool:
                raise ValueError('missing/invalid window censoring flag')
        intervals[name].append([start, end])
    summary = selected.get('summary', {})
    if not isinstance(summary, dict):
        raise ValueError('invalid audit summary')
    if (integer(summary.get('contig_count'), 'contig count', 1) != len(lengths)
            or integer(summary.get('assembly_length_bp'), 'assembly span', 1) != sum(lengths.values())
            or integer(summary.get('exact_tract_count'), 'exact tract count') != len(hits)):
        raise ValueError('audit summary counts disagree with detailed records')
    intervals = {name: union_intervals(rows) for name, rows in intervals.items()}
    return {
        'lengths': lengths, 'windows': windows, 'intervals': intervals,
        'provenance': {
            'audit_path': str(Path(path).resolve()),
            'audit_sha256': hashlib.sha256(raw).hexdigest(),
            'audit_schema_version': 1, 'audit_method': METHOD,
            'assembly_sha256': assembly_sha256,
            'assembly_accession': selected.get('assembly_accession'),
            'audit_set_id': selected.get('set_id'), 'family_key': family_key,
            'expected_outward_motif': motif, 'window_bp': window,
            'min_complete_copies': min_copies,
            'coordinate_system': '0-based half-open',
            'scope': 'exact selected-family repeats within merged assembly end windows only',
            'audited_reference_bp': sum(span(rows) for rows in windows.values()),
            'known_repeat_union_bp': sum(span(rows) for rows in intervals.values()),
            'source_hit_rows': len(hits),
            'strand_handling': 'both strands and all endpoint polarities included in overlap union',
            'fraction_denominator': 'PAF target_end - target_start; reference span including deletions',
            'changes_native_classification': False, 'changes_geometry_counts': False,
            'limitations': [
                'No-overlap means no recorded exact selected-family hit in the audited portion.',
                'Unrecorded imperfect or short repeats, other families and interior repeats can remain.',
                'Reference-span fractions are not query-base or sequence-identity fractions.',
                'Zero overlap cannot establish unique nonrepeat subtelomere or a physical chromosome end.',
                'Existing audit coordinates are reused; this module does not revalidate sequence-level matching.'
            ]
        }
    }


def annotate_alignment(index, target, start, end):
    """Annotate one mapped reference span without modifying mapping decisions."""
    if not isinstance(target, str) or target not in index['lengths']:
        raise ValueError('alignment target is not present in audit')
    integer(start, 'alignment target start')
    integer(end, 'alignment target end', 1)
    if not start < end <= index['lengths'][target]:
        raise ValueError('alignment reference coordinates out of bounds')
    total = end-start
    audited = span(intersect(index['windows'][target], start, end))
    overlapping = intersect(index['intervals'][target], start, end)
    overlap = span(overlapping)
    scope = 'full' if audited == total else 'partial' if audited else 'outside'
    status = ('known_target_repeat_overlap' if overlap else
              'no_known_overlap_in_audited_span' if scope == 'full' else
              'partial_audit_scope_no_known_overlap' if scope == 'partial' else
              'outside_audit_scope')
    return {
        'repeat_context_status': status,
        'reference_span_bp': total, 'audited_scope_status': scope,
        'audited_span_bp': audited, 'audited_span_fraction': audited/total,
        'known_target_repeat_overlap_bp': overlap,
        'known_target_repeat_overlap_fraction': overlap/total,
        'known_target_repeat_intervals': overlapping,
        'unique_nonrepeat_subtelomere_confirmed': False
    }
